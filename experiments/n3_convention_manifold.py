"""Does the ΔC arbitrariness have a shape, or is it just slack?

Two audits leave the same thing open. `n3_anatomy` showed the transplant
programme's ΔC is a convention, and that the convention decides where the
optimum lands. `n3_causal_delta_c` tried to remove the convention and found it
harder than it looks — a dictionary-free construction was *less* robust, for
reasons that look structural rather than fixable.

Neither settles whether the remaining freedom is **structured**. If every
defensible ΔC convention moves the reading along essentially one direction,
observers are not disagreeing arbitrarily: they sit at different points on a
single resolution scale, the dependence is lawful with one parameter, and it
can be named. If the conventions move it in several independent ways that each
reach the optimum, the reading is simply under-determined and there is nothing
further to say about it.

The test is possible because of one convenient fact: **the ΔC convention
changes only ΔC.** The order parameter ΔI and the capacity load come off the
same trajectories and do not depend on where the structured-overlap cut or the
frequency bin sits. So a family of conventions gives a family of ΔC curves over
one fixed scan with everything else held identical, and the question becomes
the effective dimension of that family's *consequences*.

**Calibrated before use, and the calibration changed the design.**  The obvious
statistic — the fraction of curve variance on the first principal component —
is wrong for this. A family generated by one knob sliding a peak across the
scan is intrinsically one-dimensional but geometrically *curved*, and linear
PCA charges several components to describe a curve: measured on exactly such a
synthetic family, PC1 explains only `0.767` and `rank₈₀` reads `2`, against
`0.379` and `4` for independent random curves. A registered bar of "PC1 ≥ 0.8"
would have rejected a family that is one-dimensional by construction. The
functional test does not have this failure: on the same synthetic family a
single score predicts the peak location with `r² = 0.986`, gain from PC2
`+0.001`. The full calibration table is in `convention_manifold.py`.

One further thing that table settles: the functional test answers *"is the
consequence controlled by one coordinate?"*, not *"is the family
one-dimensional?"* — a synthetic two-knob family whose second knob changes only
the peak's width still reads as functionally one-dimensional, correctly, since
that knob never moves the peak. The claims below are only ever about the
consequence.

Pre-registered predictions:

Q1. **The consequence is one-dimensional on each substrate.**  A single score
    from the shape-normalised ΔC family predicts the ΔC peak location with
    `r² ≥ 0.80`, and the second component adds `< 0.05`.  **Falsifier:** a weak
    first component or a large gain from the second — the conventions reach the
    optimum along several independent directions, and the freedom is slack
    rather than structure.

Q2. **And the axis is interpretable as resolution.**  On the Hopfield family,
    generated by one knob, the leading score is monotone in that knob
    (`|Spearman| ≥ 0.9`).  **Falsifier:** a scrambled ordering, which would
    make the low dimension an accident with no reading.

Q3. **Two independent knobs collapse onto the same axis.**  The oscillator
    family is generated by *two* conventions — entrainment tolerance and
    frequency bin width — and Q1's criterion still holds across all nine
    combinations.  **Falsifier:** it does not, so there are at least two
    directions that separately move the optimum and no single resolution scale
    exists even within one substrate.

**Disclosure — an `invariant` case was added after a smoke run, and the
thresholds were not.**  The oscillator family came back with the ΔC peak at the
same γ in eight of nine conventions and one grid step away in the ninth. `r²`
then read `0.171` and scored as a failure — but it was reporting on variance
that does not exist: with a target quantised to the scan grid and spanning one
step, there is nothing for an axis to explain, and the number is driven entirely
by which side of a tie a single outlier fell.  A consequence that does not move
is a **stronger** result than one that moves along a line, so scoring it as a
failure inverts the finding.  `explained_by` now flags a target whose spread is
within one grid step as `invariant` and declines to compute `r²` for it; the
registered `r² ≥ 0.80` and `gain < 0.05` bars are unchanged and still apply
wherever the target genuinely varies.  This is the same failure mode as the
saturated arms in `n3_causal_delta_c`: a statistic answering confidently on data
that cannot support the question.

Honest scope.  The families are the ones each substrate's dictionary exposes,
over the ranges `n3_anatomy` already established as defensible; other
conventions may exist that move the reading differently. "One axis" here is a
statement about a finite family sampled on a grid, not a proof about the space
of all admissible ΔC definitions. And a positive result would not make the
choice go away — it would say the choice is a single interpretable knob rather
than an open set, which is a weaker and more useful claim.

    python experiments/n3_convention_manifold.py
    python experiments/n3_convention_manifold.py --quick
"""

